#!/usr/bin/env python3
"""从受控字典 ``contracts/scene-taxonomy.yaml`` 生成前端常量 ``frontend/src/constants/sceneTaxonomy.ts``。

设计：受控字典为单一事实来源（数据驱动，可持续扩充）。前端不再手写 18 值 SceneType 联合，
而是由本脚本按 YAML 生成联合类型 + 中文标签 + 分类映射，杜绝前后端取值域漂移。

用法（仓库根目录）::

    python3 scripts/gen_scene_taxonomy_ts.py            # 生成/覆盖 sceneTaxonomy.ts
    python3 scripts/gen_scene_taxonomy_ts.py --check    # 仅校验现有产物与字典是否一致（CI 用，不一致退出 1）
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
TAXONOMY_PATH = ROOT / "contracts" / "scene-taxonomy.yaml"
OUTPUT_PATH = ROOT / "frontend" / "src" / "constants" / "sceneTaxonomy.ts"


def _load() -> dict:
    if not TAXONOMY_PATH.is_file():
        raise SystemExit(f"[error] 未找到受控字典：{TAXONOMY_PATH}")
    return yaml.safe_load(TAXONOMY_PATH.read_text(encoding="utf-8")) or {}


def _ts_str(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _union(values: list[str]) -> str:
    if not values:
        return "string"
    return " | ".join(_ts_str(v) for v in values)


def _render_map(entries: list[tuple[str, str]], indent: str = "  ") -> str:
    lines = [f"{indent}{key}: {_ts_str(val)}," for key, val in entries]
    return "\n".join(lines)


def _render_array(values: list[str], indent: str = "    ") -> str:
    return "\n".join(f"{indent}{_ts_str(v)}," for v in values)


def generate(doc: dict) -> str:
    categories = [(c["value"], c.get("label", c["value"])) for c in doc.get("categories", [])]
    scene_types = doc.get("scene_types", [])
    scene_cat_values = [t["value"] for t in scene_types]
    scene_cat_entries = [(t["value"], t.get("label", t["value"])) for t in scene_types]
    type_to_cat = {t["value"]: t["category"] for t in scene_types}

    # 分类 → 类型（保持 YAML 声明顺序）
    by_cat: dict[str, list[str]] = {value: [] for value, _ in categories}
    for t in scene_types:
        by_cat.setdefault(t["category"], []).append(t["value"])

    behavior = [(b["value"], b.get("label", b["value"])) for b in doc.get("behavior_types", [])]
    action = [(a["value"], a.get("label", a["value"])) for a in doc.get("action_types", [])]
    condition = [(c["value"], c.get("label", c["value"])) for c in doc.get("trigger_condition_types", [])]

    out: list[str] = []
    out.append("/**")
    out.append(" * AUTO-GENERATED by scripts/gen_scene_taxonomy_ts.py —— 请勿手工编辑。")
    out.append(" * 单一事实来源：contracts/scene-taxonomy.yaml（可扩展受控字典，取消固定 18 值枚举）。")
    out.append(" * 修改取值域请编辑该 YAML 后重新运行：python3 scripts/gen_scene_taxonomy_ts.py")
    out.append(f" * version: {doc.get('version', '?')} / status: {doc.get('status', '?')}")
    out.append(" */")
    out.append("")
    out.append(f"export type SceneType = {_union(scene_cat_values)}")
    out.append("")
    out.append(f"export type SceneCategory = {_union([v for v, _ in categories])}")
    out.append("")
    out.append("export const SCENE_TYPE_LABELS: Record<string, string> = {")
    out.append(_render_map(scene_cat_entries))
    out.append("}")
    out.append("")
    out.append("export const SCENE_CATEGORY_LABELS: Record<string, string> = {")
    out.append(_render_map(categories))
    out.append("}")
    out.append("")
    out.append("export const SCENE_CATEGORY_BY_TYPE: Record<string, string> = {")
    out.append(_render_map([(v, type_to_cat[v]) for v in scene_cat_values]))
    out.append("}")
    out.append("")
    out.append("export const SCENE_TYPES_BY_CATEGORY: Record<string, readonly SceneType[]> = {")
    for value, _label in categories:
        out.append(f"  {_ts_str(value)}: [")
        out.append(_render_array(by_cat.get(value, [])))
        out.append("  ],")
    out.append("}")
    out.append("")
    # 行为 / 动作 / 触发条件（供编辑器下拉候选；均取自受控字典）
    out.append(f"export type BehaviorType = {_union([v for v, _ in behavior])}")
    out.append("")
    out.append("export const BEHAVIOR_TYPE_LABELS: Record<string, string> = {")
    out.append(_render_map(behavior))
    out.append("}")
    out.append("")
    out.append(f"export type ActionType = {_union([v for v, _ in action])}")
    out.append("")
    out.append("export const ACTION_TYPE_LABELS: Record<string, string> = {")
    out.append(_render_map(action))
    out.append("}")
    out.append("")
    out.append(f"export type TriggerConditionType = {_union([v for v, _ in condition])}")
    out.append("")
    out.append("export const TRIGGER_CONDITION_TYPE_LABELS: Record<string, string> = {")
    out.append(_render_map(condition))
    out.append("}")
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="从 scene-taxonomy.yaml 生成前端常量")
    parser.add_argument("--check", action="store_true", help="仅校验现有产物与字典一致（CI 用，不写文件）")
    args = parser.parse_args(argv)

    content = generate(_load())
    if args.check:
        existing = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.is_file() else ""
        if existing != content:
            print(f"[check] sceneTaxonomy.ts 与字典不一致，请运行 gen_scene_taxonomy_ts.py 重新生成：{OUTPUT_PATH}", file=sys.stderr)
            return 1
        print("[check] sceneTaxonomy.ts 与受控字典一致")
        return 0
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(content, encoding="utf-8")
    print(f"[ok] 已生成 {OUTPUT_PATH.relative_to(ROOT)}（{len(content.splitlines())} 行）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
